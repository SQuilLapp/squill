using Squill.Core;
using Squill.Core.Design;

namespace Squill.Sql.Ddl;

/// <summary>Builds the parts of CREATE and DROP statements shared by the four dialects.</summary>
internal static class DdlWriter
{
    /// <summary>Builds the CREATE TABLE statement and its CREATE INDEX statements.</summary>
    public static IReadOnlyList<string> CreateTable(TableDesign table, DatabaseDialect d)
    {
        ArgumentNullException.ThrowIfNull(table);
        if (table.Columns.Count == 0)
        {
            throw new ArgumentException("A table needs at least one column.", nameof(table));
        }

        var rowidKey = d == DatabaseDialect.Sqlite && table.PrimaryKey.Count == 1
            && table.Columns.Any(c => c.IsAutoIncrement && c.Name == table.PrimaryKey[0]) ? table.PrimaryKey[0] : null;

        var clauses = table.Columns.Select(c => Column(c, d, c.Name == rowidKey)).ToList();
        if (table.PrimaryKey.Count > 0 && rowidKey is null)
        {
            var name = table.PrimaryKeyName is null ? "" : $"CONSTRAINT {SqlQuoting.Quote(table.PrimaryKeyName, d)} ";
            clauses.Add($"{name}PRIMARY KEY ({Columns(table.PrimaryKey, d)})");
        }

        clauses.AddRange(table.ForeignKeys.Select(f => ForeignKey(f, d)));

        var qualified = SqlQuoting.QualifiedName(table.Schema, table.Name, d);
        var statements = new List<string>
        {
            $"CREATE TABLE {qualified} (\n    {string.Join(",\n    ", clauses)}\n)",
        };
        statements.AddRange(table.Indexes.Select(i => CreateIndex(table.Schema, qualified, i, d)));
        return statements;
    }

    /// <summary>Builds the CREATE INDEX statement.</summary>
    public static string CreateIndex(string? schema, string qualifiedTable, IndexDesign i, DatabaseDialect d) =>
        $"CREATE {(i.IsUnique ? "UNIQUE " : "")}INDEX {IndexName(schema, i.Name, d)} ON {qualifiedTable} ({Columns(i.Columns, d)})";

    /// <summary>Builds the <c>CONSTRAINT ... FOREIGN KEY</c> clause.</summary>
    public static string ForeignKey(ForeignKeyDesign f, DatabaseDialect d) =>
        $"CONSTRAINT {SqlQuoting.Quote(f.Name, d)} FOREIGN KEY ({Columns(f.Columns, d)}) "
        + $"REFERENCES {SqlQuoting.QualifiedName(f.ReferencedSchema, f.ReferencedTable, d)} ({Columns(f.ReferencedColumns, d)}) "
        + $"ON DELETE {Action(f.OnDelete, d)} ON UPDATE {Action(f.OnUpdate, d)}";

    // SQL Server has no RESTRICT keyword; NO ACTION is its equivalent.
    private static string Action(ReferentialAction a, DatabaseDialect d) =>
        d == DatabaseDialect.SqlServer && a == ReferentialAction.Restrict ? "NO ACTION" : a.ToSql();

    /// <summary>Builds the DROP TABLE statement.</summary>
    public static IReadOnlyList<string> DropTable(string? schema, string name, DatabaseDialect d) =>
        [$"DROP TABLE {SqlQuoting.QualifiedName(schema, name, d)}"];

    /// <summary>Quotes and joins column names.</summary>
    public static string Columns(IEnumerable<string> names, DatabaseDialect d) =>
        string.Join(", ", names.Select(n => SqlQuoting.Quote(n, d)));

    private static string IndexName(string? schema, string name, DatabaseDialect d) =>
        d == DatabaseDialect.Sqlite && schema != "main"
            ? SqlQuoting.QualifiedName(schema, name, d)
            : SqlQuoting.Quote(name, d);

    /// <summary>Builds a column definition clause.</summary>
    public static string Column(ColumnDesign c, DatabaseDialect d, bool rowidAlias)
    {
        var name = SqlQuoting.Quote(c.Name, d);
        if (rowidAlias)
        {
            return $"{name} INTEGER PRIMARY KEY AUTOINCREMENT";
        }

        var sql = $"{name} {c.DataType}";
        if (c.IsAutoIncrement)
        {
            sql += d switch
            {
                DatabaseDialect.PostgreSql => " GENERATED BY DEFAULT AS IDENTITY",
                DatabaseDialect.MySql => " AUTO_INCREMENT",
                DatabaseDialect.SqlServer => " IDENTITY(1,1)",
                _ => "",
            };
        }

        if (!c.IsNullable)
        {
            sql += " NOT NULL";
        }
        else if (d == DatabaseDialect.SqlServer)
        {
            sql += " NULL";
        }

        // A default next to an identity column is invalid on every engine, so the generated value wins.
        return string.IsNullOrWhiteSpace(c.DefaultExpression) || c.IsAutoIncrement ? sql : $"{sql} DEFAULT {c.DefaultExpression}";
    }
}
