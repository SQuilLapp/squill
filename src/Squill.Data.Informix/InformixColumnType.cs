using System.Globalization;

namespace Squill.Data.Informix;

/// <summary>Decodes the packed <c>syscolumns.coltype</c> / <c>collength</c> / <c>extended_id</c> of an Informix column into type text.</summary>
internal static class InformixColumnType
{
    private const int NotNullBit = 256;

    /// <summary>Tells whether the NOT NULL bit (256) of <c>coltype</c> is set.</summary>
    /// <param name="coltype">The raw <c>syscolumns.coltype</c>.</param>
    /// <returns><see langword="true"/> when the column rejects NULL.</returns>
    public static bool IsNotNull(int coltype) => (coltype & NotNullBit) != 0;

    /// <summary>Tells whether the type is generated by the server (<c>SERIAL</c>, <c>SERIAL8</c>, <c>BIGSERIAL</c>).</summary>
    /// <param name="coltype">The raw <c>syscolumns.coltype</c>.</param>
    /// <returns><see langword="true"/> for the three serial types.</returns>
    public static bool IsSerial(int coltype) => (coltype % 256) is 6 or 18 or 53;

    /// <summary>Gives the type text of a column, for example <c>VARCHAR(40)</c> or <c>DATETIME YEAR TO FRACTION(5)</c>.</summary>
    /// <param name="coltype">The raw <c>syscolumns.coltype</c>; the flag bits above 255 are ignored.</param>
    /// <param name="collength">The raw <c>syscolumns.collength</c>, whose meaning depends on the type.</param>
    /// <param name="extendedId">The <c>syscolumns.extended_id</c>, which names the opaque type of codes 40 and 41.</param>
    /// <returns>The type text; <c>unknown(&lt;code&gt;)</c> for a code this table does not know, never an exception.</returns>
    public static string Decode(int coltype, int collength, int extendedId)
    {
        var code = coltype % 256;
        return code switch
        {
            0 => $"CHAR({Length(collength)})",
            1 => "SMALLINT",
            2 => "INTEGER",
            3 => "FLOAT",
            4 => "SMALLFLOAT",
            5 => Decimal("DECIMAL", collength),
            6 => "SERIAL",
            7 => "DATE",
            8 => Decimal("MONEY", collength),
            10 => "DATETIME " + Qualifier(collength, false),
            11 => "BYTE",
            12 => "TEXT",
            13 => Varying("VARCHAR", collength),
            14 => "INTERVAL " + Qualifier(collength, true),
            15 => $"NCHAR({Length(collength)})",
            16 => Varying("NVARCHAR", collength),
            17 => "INT8",
            18 => "SERIAL8",
            19 => "SET",
            20 => "MULTISET",
            21 => "LIST",
            22 => "ROW",
            23 => "COLLECTION",
            43 => $"LVARCHAR({Length(collength)})",
            45 => "BOOLEAN",
            52 => "BIGINT",
            53 => "BIGSERIAL",
            40 or 41 => extendedId switch
            {
                1 => $"LVARCHAR({Length(collength)})",
                5 => "BOOLEAN",
                10 => "BLOB",
                11 => "CLOB",
                _ => Unknown(code),
            },
            _ => Unknown(code),
        };
    }

    private static string Unknown(int code) => $"unknown({code.ToString(CultureInfo.InvariantCulture)})";

    // Lengths above 32767 are stored as negative 16-bit values.
    private static int Length(int collength) => collength < 0 ? collength + 65536 : collength;

    // High byte = minimum reserved space, low byte = maximum length; 255 as scale marks a floating-point DECIMAL.
    private static string Varying(string name, int collength) =>
        collength / 256 == 0 ? $"{name}({collength % 256})" : $"{name}({collength % 256},{collength / 256})";

    private static string Decimal(string name, int collength) =>
        collength % 256 == 255 ? $"{name}({collength / 256})" : $"{name}({collength / 256},{collength % 256})";

    private static readonly string[] Units = ["YEAR", "", "MONTH", "", "DAY", "", "HOUR", "", "MINUTE", "", "SECOND"];

    // collength = total digits * 256 + first unit * 16 + last unit; the units are 0, 2, 4, 6, 8, 10 and 11..15 for FRACTION(1..5).
    private static string Qualifier(int collength, bool interval)
    {
        int first = collength / 16 % 16, last = collength % 16, total = collength / 256;
        return Unit(first, interval ? total - TrailingDigits(first, last) : 0) + " TO " + Unit(last, 0);
    }

    // Digits of every unit after the first one (2 each, the fraction as many as its number).
    private static int TrailingDigits(int first, int last)
    {
        var digits = 0;
        for (var u = first + 2; u <= Math.Min(last, 10); u += 2)
            digits += 2;
        return last >= 11 ? digits + last - 10 : digits;
    }

    private static string Unit(int code, int leading)
    {
        if (code >= 11)
            return $"FRACTION({code - 10})";
        var name = code < Units.Length && Units[code].Length > 0 ? Units[code] : "UNKNOWN";
        return leading is > 0 and not 2 ? $"{name}({leading})" : name;
    }
}
