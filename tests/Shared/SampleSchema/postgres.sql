-- SQuilL sample schema for PostgreSQL. Idempotent: safe to run twice.
drop schema if exists sample cascade;
create schema sample;

create type sample.mood as enum ('sad', 'ok', 'happy');

create table sample.customers (
    id integer generated always as identity primary key,
    name varchar(100) not null,
    email text unique,
    created_at timestamptz not null default now()
);

create table sample.orders (
    id serial primary key,
    customer_id integer not null references sample.customers (id) on delete cascade on update cascade,
    placed_on date not null default current_date,
    total numeric(18, 4) not null default 0
);
create index orders_customer_placed on sample.orders (customer_id, placed_on);

create table sample.order_items (
    order_id integer not null references sample.orders (id) on delete cascade,
    line_no integer not null,
    sku varchar(30) not null,
    quantity integer not null default 1,
    primary key (order_id, line_no)
);

-- One foreign key per referential action.
create table sample.fk_targets (id integer primary key);
create table sample.fk_actions (
    id integer primary key,
    a integer references sample.fk_targets (id) on delete cascade,
    b integer references sample.fk_targets (id) on delete set null,
    c integer references sample.fk_targets (id) on delete restrict,
    d integer references sample.fk_targets (id) on delete no action,
    e integer default 0 references sample.fk_targets (id) on delete set default
);

create table sample.no_pk (label text, amount integer);

create view sample.order_totals as
    select c.id as customer_id, c.name, count(o.id) as orders, coalesce(sum(o.total), 0) as total
    from sample.customers c left join sample.orders o on o.customer_id = c.id
    group by c.id, c.name;

create table sample.all_types (
    c_smallint smallint,
    c_integer integer,
    c_bigint bigint,
    c_numeric numeric(18, 4),
    c_real real,
    c_double double precision,
    c_boolean boolean,
    c_text text,
    c_varchar varchar(50),
    c_char char(3),
    c_bytea bytea,
    c_date date,
    c_time time,
    c_timestamp timestamp,
    c_timestamptz timestamptz,
    c_interval interval,
    c_uuid uuid,
    c_json json,
    c_jsonb jsonb,
    c_inet inet,
    c_int_array integer[],
    c_text_array text[],
    c_enum sample.mood,
    c_serial serial,
    c_identity integer generated by default as identity
);
