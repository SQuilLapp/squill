using Squill.Core;
using Squill.Core.Plans;
using Squill.Data.RoundTrip;
using Xunit;

namespace Squill.Data.Oracle.Tests;

public sealed class PlanScenarioTests(OracleFixture server) : IClassFixture<OracleFixture>
{
    private const string Slow = "select count(*) from all_objects a, all_objects b, all_objects c";

    private ValueTask<IDatabaseConnection> OpenAsync(string user) =>
        new OracleDatabaseProvider().OpenAsync(
            new ConnectionProfile(Guid.NewGuid(), "plan", DatabaseDialect.Oracle, server.Host, server.Port, OracleFixture.Service, user, null, null),
            OracleFixture.Password, CancellationToken.None);

    [Fact(Skip = DockerGate.SkipReason, SkipUnless = nameof(DockerGate.Enabled), SkipType = typeof(DockerGate))]
    public async Task SampleStatements_GiveUsablePlans_AndTheConnectionStillRuns()
    {
        await using var connection = await OpenAsync(OracleFixture.UserName);
        async Task ExecAsync(string sql)
        {
            await using var reader = await connection.ExecuteAsync(sql, [], CancellationToken.None);
            await reader.ReadAllAsync(10, CancellationToken.None);
        }

        await ExecAsync("create table customers (id number generated by default as identity primary key, name varchar2(60) not null, email varchar2(120))");
        await ExecAsync("create table orders (id number generated by default as identity primary key, customer_id number not null references customers (id), total number(10, 2) not null)");
        try
        {
            var spec = new PlanSpec(DatabaseDialect.Oracle, "", false, Slow, HasCost: true, HasActual: true, RolledBackOnActual: false, FetchFirst: true);
            await PlanScenario.SeedAsync(connection, spec);

            // The application user has no V$ access: the actual plan says so instead of failing obscurely, and the estimated plan still works.
            var reader = Assert.IsAssignableFrom<IPlanReader>(connection);
            var refused = await Assert.ThrowsAsync<PlanUnavailableException>(async () => await reader.ExplainAsync("select name from customers", [], PlanMode.Actual, CancellationToken.None));
            Assert.Contains("SELECT_CATALOG_ROLE", refused.Message, StringComparison.Ordinal);
            Assert.NotNull(await reader.ExplainAsync("select name from customers", [], PlanMode.Estimated, CancellationToken.None));

            // Roles are read at login: grant, then reconnect.
            await using (var admin = await OpenAsync("system"))
                await using (var grant = await admin.ExecuteAsync($"grant select_catalog_role to {OracleFixture.UserName}", [], CancellationToken.None))
                    await grant.ReadAllAsync(1, CancellationToken.None);
            await using var granted = await OpenAsync(OracleFixture.UserName);
            await PlanScenario.RunAsync(granted, spec);
        }
        finally
        {
            await ExecAsync("drop table orders");
            await ExecAsync("drop table customers");
        }
    }
}
