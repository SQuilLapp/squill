using Squill.Core;
using Squill.Core.Editing;
using Squill.Presentation.Editing;
using Squill.Sql.Editing;
using Xunit;

namespace Squill.Data.Oracle.Tests;

public sealed class GridEditTests(OracleFixture server) : IClassFixture<OracleFixture>
{
    [Fact(Skip = DockerGate.SkipReason, SkipUnless = nameof(DockerGate.Enabled), SkipType = typeof(DockerGate))]
    public async Task PlainSelect_IsEditable_AndTheCommitReadsTheGeneratedKeyBack()
    {
        await using var connection = await new OracleDatabaseProvider().OpenAsync(
            new ConnectionProfile(Guid.NewGuid(), "ora", DatabaseDialect.Oracle, server.Host, server.Port, OracleFixture.Service, OracleFixture.UserName, null, null),
            OracleFixture.Password, CancellationToken.None);
        async Task<List<object?[]>> QueryAsync(string sql)
        {
            await using var reader = await connection.ExecuteAsync(sql, [], CancellationToken.None);
            return await reader.ReadAllAsync(100, CancellationToken.None);
        }

        await QueryAsync("create table squill_ge (id number generated by default as identity primary key, name varchar2(40), seen date)");
        try
        {
            var schema = await connection.ReadSchemaAsync(CancellationToken.None);
            List<ColumnInfo> columns;
            await using (var meta = await connection.ExecuteAsync("select * from squill_ge", [], CancellationToken.None))
                columns = [.. meta.Columns];
            var verdict = EditableSourceAnalyzer.Analyze("select * from squill_ge", DatabaseDialect.Oracle, schema, columns);
            var target = Assert.IsType<EditTarget>(verdict.Target);
            Assert.Equal(["ID"], target.KeyColumns);

            var committer = new EditCommitter(connection, DatabaseDialect.Oracle);
            var seen = new DateTime(2024, 5, 6, 7, 8, 9);
            var first = await committer.CommitAsync(target, columns, [new PendingEdit(0, new InsertRow([new ColumnValue("NAME", "a"), new ColumnValue("SEEN", seen)]))], CancellationToken.None);
            var key = Assert.Single(first.GeneratedKeys);
            Assert.Equal(0L, key.Key);
            Assert.NotNull(key.Value);

            await committer.CommitAsync(target, columns, [new PendingEdit(0, new UpdateRow([new ColumnValue("ID", key.Value)], [new ColumnValue("NAME", "b")]))], CancellationToken.None);
            var row = Assert.Single(await QueryAsync("select id, name, seen from squill_ge"));
            Assert.Equal(("b", seen), (row[1], row[2]));

            await committer.CommitAsync(target, columns, [new PendingEdit(0, new DeleteRow([new ColumnValue("ID", key.Value)]))], CancellationToken.None);
            Assert.Empty(await QueryAsync("select id from squill_ge"));
        }
        finally
        {
            await QueryAsync("drop table squill_ge");
        }
    }
}
