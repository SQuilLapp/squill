using System.Globalization;
using System.Text;
using Xunit;

namespace Squill.Presentation.Tests.I18n;

/// <summary>Writes <c>docs/tasks/phase-10/inventory.md</c> when <c>SQUILL_WRITE_INVENTORY=1</c>.</summary>
public sealed class InventoryGenerator
{
    /// <summary>Gate of <see cref="Write"/>.</summary>
    public static bool IsRequested => Environment.GetEnvironmentVariable("SQUILL_WRITE_INVENTORY") == "1";

    /// <summary>Renders the inventory markdown of the given candidates.</summary>
    public static string Render(IReadOnlyList<StringCandidate> all)
    {
        var heads = new[] { "shared", "avalonia", "winui" };
        var sb = new StringBuilder();
        sb.Append("# Phase 10 inventory of hard-coded strings\n\n");
        sb.Append("Generated by P10-03 (`SQUILL_WRITE_INVENTORY=1`), not regenerated afterwards. Tick a line when done: `- [x] ... -> key` or `-> ignored`.\n\n");
        sb.Append("## Summary\n\n| Area | shared | avalonia | winui | total |\n|---|---:|---:|---:|---:|\n");
        var areas = all.Select(c => HardcodedStringScanner.AreaOf(c.Path)).Distinct().Order(StringComparer.Ordinal).ToList();
        foreach (var area in areas)
        {
            var inArea = all.Where(c => HardcodedStringScanner.AreaOf(c.Path) == area).ToList();
            sb.Append(CultureInfo.InvariantCulture, $"| {area} | {string.Join(" | ", heads.Select(h => inArea.Count(c => HardcodedStringScanner.HeadOf(c.Path) == h)))} | {inArea.Count} |\n");
        }

        sb.Append(CultureInfo.InvariantCulture, $"| **total** | {string.Join(" | ", heads.Select(h => all.Count(c => HardcodedStringScanner.HeadOf(c.Path) == h)))} | {all.Count} |\n");
        foreach (var area in areas)
        {
            sb.Append(CultureInfo.InvariantCulture, $"\n## {area}\n");
            foreach (var file in all.Where(c => HardcodedStringScanner.AreaOf(c.Path) == area).GroupBy(c => c.Path).OrderBy(g => g.Key, StringComparer.Ordinal))
            {
                sb.Append(CultureInfo.InvariantCulture, $"\n### {file.Key}\n\n");
                foreach (var c in file.OrderBy(c => c.Line).ThenBy(c => c.Text, StringComparer.Ordinal))
                    sb.Append(CultureInfo.InvariantCulture, $"- [ ] {c.Path}:{c.Line}  {c.Kind}  \"{c.Text}\"\n");
            }
        }

        return sb.ToString();
    }

    /// <summary>Scans the repository and writes the inventory file.</summary>
    [Fact(Skip = "Set SQUILL_WRITE_INVENTORY=1 to write docs/tasks/phase-10/inventory.md.", SkipUnless = nameof(IsRequested), SkipType = typeof(InventoryGenerator))]
    public void Write()
    {
        var root = HardcodedStringScanner.FindRepositoryRoot();
        File.WriteAllText(Path.Combine(root, "docs", "tasks", "phase-10", "inventory.md"), Render(HardcodedStringScanner.ScanRepository(root)));
    }
}
