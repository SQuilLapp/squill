using Squill.Core;
using Squill.Sql.Transactions;
using Xunit;

namespace Squill.Sql.Tests.Transactions;

public sealed class StatementClassifierTests
{
    private const DatabaseDialect Pg = DatabaseDialect.PostgreSql;
    private const DatabaseDialect My = DatabaseDialect.MySql;
    private const DatabaseDialect Ms = DatabaseDialect.SqlServer;
    private const DatabaseDialect Lite = DatabaseDialect.Sqlite;

    private static StatementTraits C(string sql, DatabaseDialect d) => StatementClassifier.Classify(sql, d);

    [Theory]
    [InlineData("", Pg, StatementKind.Empty)]
    [InlineData("  -- only a comment\n /* x */ ;", My, StatementKind.Empty)]
    [InlineData("select 1", Pg, StatementKind.Select)]
    [InlineData("/* lead */ -- more\n  SELECT * FROM t;", Ms, StatementKind.Select)]
    [InlineData("(select 1) union (select 2)", Pg, StatementKind.Select)]
    [InlineData("values (1)", Lite, StatementKind.Select)]
    [InlineData("table t", My, StatementKind.Select)]
    [InlineData("with a as (select 1) select * from a", Pg, StatementKind.Select)]
    [InlineData("with a as (select 1) delete from t", Pg, StatementKind.Delete)]
    [InlineData("with a as (select 1) update t set x = 1", Ms, StatementKind.Update)]
    [InlineData("with a as (select 1) insert into t select * from a", Lite, StatementKind.Insert)]
    [InlineData("insert into t values (1)", Pg, StatementKind.Insert)]
    [InlineData("insert or replace into t values (1)", Lite, StatementKind.Insert)]
    [InlineData("replace into t values (1)", My, StatementKind.Insert)]
    [InlineData("replace into t values (1)", Lite, StatementKind.Insert)]
    [InlineData("update t set a = 1 where id = 2", Pg, StatementKind.Update)]
    [InlineData("delete from t where id = 2", Ms, StatementKind.Delete)]
    [InlineData("merge into t using s on t.id = s.id when matched then delete", Pg, StatementKind.Merge)]
    [InlineData("truncate table t", My, StatementKind.Truncate)]
    [InlineData("create table t (a int)", Pg, StatementKind.Create)]
    [InlineData("alter table t add b int", Ms, StatementKind.Alter)]
    [InlineData("rename table a to b", My, StatementKind.Alter)]
    [InlineData("comment on table t is 'x'", Pg, StatementKind.Alter)]
    [InlineData("grant select on t to u", Pg, StatementKind.Alter)]
    [InlineData("revoke select on t from u", Pg, StatementKind.Alter)]
    [InlineData("drop table t", Lite, StatementKind.Drop)]
    [InlineData("begin", Pg, StatementKind.Transaction)]
    [InlineData("commit", My, StatementKind.Transaction)]
    [InlineData("call p()", My, StatementKind.Call)]
    [InlineData("exec p", Ms, StatementKind.Call)]
    [InlineData("execute p", Ms, StatementKind.Call)]
    [InlineData("do $$ begin end $$", Pg, StatementKind.Call)]
    [InlineData("set search_path = x", Pg, StatementKind.Set)]
    [InlineData("pragma foreign_keys = on", Lite, StatementKind.Set)]
    [InlineData("use db", My, StatementKind.Set)]
    [InlineData("show tables", My, StatementKind.Set)]
    [InlineData("vacuum", Pg, StatementKind.Other)]
    [InlineData("explain select 1", Pg, StatementKind.Other)]
    [InlineData("begin try select 1 end try", Ms, StatementKind.Other)]
    [InlineData("end try", Ms, StatementKind.Other)]
    [InlineData("foo bar", Pg, StatementKind.Other)]
    [InlineData("select 1; delete from t", Pg, StatementKind.Select)]
    [InlineData(";; select 1", Pg, StatementKind.Select)]
    public void Kind(string sql, DatabaseDialect d, StatementKind expected) => Assert.Equal(expected, C(sql, d).Kind);

    [Theory]
    [InlineData("", Pg, true)]
    [InlineData("select 1", Pg, true)]
    [InlineData("select * from t for update", Pg, true)]
    [InlineData("select * from t for no key update", Pg, true)]
    [InlineData("select insert('abc', 1, 1, 'x')", My, true)]
    [InlineData("with a as (select 1) select * from a", Pg, true)]
    [InlineData("select * into t2 from t", Ms, false)]
    [InlineData("with a as (delete from t returning *) select * from a", Pg, false)]
    [InlineData("set x = 1", Pg, true)]
    [InlineData("pragma user_version", Lite, true)]
    [InlineData("rollback", Pg, true)]
    [InlineData("commit", Pg, false)]
    [InlineData("begin", Pg, false)]
    [InlineData("insert into t values (1)", Pg, false)]
    [InlineData("update t set a = 1", Pg, false)]
    [InlineData("create table t (a int)", Pg, false)]
    [InlineData("call p()", My, false)]
    [InlineData("exec p", Ms, false)]
    [InlineData("do $$ x $$", Pg, false)]
    [InlineData("vacuum", Lite, false)]
    [InlineData("foo", Pg, false)]
    public void ReadOnly(string sql, DatabaseDialect d, bool expected) => Assert.Equal(expected, C(sql, d).ReadOnly);

    [Theory]
    [InlineData("insert into t values (1)", Pg, true)]
    [InlineData("update t set a = 1", My, true)]
    [InlineData("delete from t", Ms, true)]
    [InlineData("merge into t using s on 1=1 when matched then delete", Pg, true)]
    [InlineData("truncate t", Pg, true)]
    [InlineData("select * into t2 from t", Ms, true)]
    [InlineData("replace into t values (1)", My, true)]
    [InlineData("insert or ignore into t values (1)", Lite, true)]
    [InlineData("with a as (select 1) delete from t", Pg, true)]
    [InlineData("select 1", Pg, false)]
    [InlineData("create table t (a int)", Pg, false)]
    [InlineData("call p()", My, false)]
    [InlineData("foo", Pg, false)]
    public void ModifiesData(string sql, DatabaseDialect d, bool expected) => Assert.Equal(expected, C(sql, d).ModifiesData);

    [Theory]
    [InlineData("create table t (a int)", Pg, true)]
    [InlineData("alter table t add b int", My, true)]
    [InlineData("drop index i", Ms, true)]
    [InlineData("truncate t", Pg, true)]
    [InlineData("rename table a to b", My, true)]
    [InlineData("comment on column t.a is 'x'", Pg, true)]
    [InlineData("grant all on t to u", Pg, true)]
    [InlineData("revoke all on t from u", My, true)]
    [InlineData("insert into t values (1)", Pg, false)]
    [InlineData("select 1", Pg, false)]
    [InlineData("call p()", Pg, false)]
    [InlineData("foo", Pg, false)]
    public void ChangesSchema(string sql, DatabaseDialect d, bool expected) => Assert.Equal(expected, C(sql, d).ChangesSchema);

    [Theory]
    [InlineData("update t set a = 1", Pg, true, true)]
    [InlineData("update t set a = 1 where id = 1", Pg, false, false)]
    [InlineData("delete from t", My, true, true)]
    [InlineData("delete from t where id = 1", My, false, false)]
    [InlineData("delete from t where id in (select 1)", Ms, false, false)]
    [InlineData("delete from t using (select 1 where 1 = 1) s", Pg, true, true)]
    [InlineData("update t set a = (select 1 from u where u.id = 1)", Pg, true, true)]
    [InlineData("update t set a = 1 where current of c", Pg, false, false)]
    [InlineData("with a as (select 1 where 1 = 1) delete from t", Pg, true, true)]
    [InlineData("with a as (select 1) delete from t where id = 1", Pg, false, false)]
    [InlineData("truncate table t", Pg, false, true)]
    [InlineData("drop table t", Pg, false, true)]
    [InlineData("alter table t drop column a", Pg, false, true)]
    [InlineData("alter table t add column a int", Pg, false, false)]
    [InlineData("insert into t values (1)", Pg, false, false)]
    [InlineData("select 1", Pg, false, false)]
    public void NoWhereAndDestructive(string sql, DatabaseDialect d, bool noWhere, bool destructive)
    {
        var t = C(sql, d);
        Assert.Equal(noWhere, t.NoWhere);
        Assert.Equal(destructive, t.Destructive);
    }

    [Theory]
    [InlineData("BEGIN", Pg, TransactionControl.Begin)]
    [InlineData("begin transaction", Lite, TransactionControl.Begin)]
    [InlineData("begin work", Pg, TransactionControl.Begin)]
    [InlineData("begin immediate", Lite, TransactionControl.Begin)]
    [InlineData("start transaction", My, TransactionControl.Begin)]
    [InlineData("start transaction read only", Pg, TransactionControl.Begin)]
    [InlineData("begin", My, TransactionControl.Begin)]
    [InlineData("begin tran", Ms, TransactionControl.Begin)]
    [InlineData("begin transaction t1", Ms, TransactionControl.Begin)]
    [InlineData("begin try", Ms, TransactionControl.None)]
    [InlineData("start slave", My, TransactionControl.None)]
    [InlineData("commit", Pg, TransactionControl.Commit)]
    [InlineData("commit work", My, TransactionControl.Commit)]
    [InlineData("commit transaction", Ms, TransactionControl.Commit)]
    [InlineData("commit tran", Ms, TransactionControl.Commit)]
    [InlineData("end", Pg, TransactionControl.Commit)]
    [InlineData("end transaction", Lite, TransactionControl.Commit)]
    [InlineData("end", Ms, TransactionControl.None)]
    [InlineData("rollback", Pg, TransactionControl.Rollback)]
    [InlineData("rollback work", My, TransactionControl.Rollback)]
    [InlineData("rollback transaction", Ms, TransactionControl.Rollback)]
    [InlineData("rollback tran", Ms, TransactionControl.Rollback)]
    [InlineData("abort", Pg, TransactionControl.Rollback)]
    [InlineData("rollback to sp1", Pg, TransactionControl.RollbackToSavepoint)]
    [InlineData("rollback to savepoint sp1", My, TransactionControl.RollbackToSavepoint)]
    [InlineData("rollback transaction to sp1", Pg, TransactionControl.RollbackToSavepoint)]
    [InlineData("rollback transaction sp1", Ms, TransactionControl.RollbackToSavepoint)]
    [InlineData("rollback tran @name", Ms, TransactionControl.RollbackToSavepoint)]
    [InlineData("savepoint sp1", Pg, TransactionControl.Savepoint)]
    [InlineData("savepoint sp1", Lite, TransactionControl.Savepoint)]
    [InlineData("save transaction sp1", Ms, TransactionControl.Savepoint)]
    [InlineData("save tran sp1", Ms, TransactionControl.Savepoint)]
    [InlineData("save transaction sp1", Pg, TransactionControl.None)]
    [InlineData("release sp1", Lite, TransactionControl.ReleaseSavepoint)]
    [InlineData("release savepoint sp1", Pg, TransactionControl.ReleaseSavepoint)]
    [InlineData("select 1", Pg, TransactionControl.None)]
    public void Control(string sql, DatabaseDialect d, TransactionControl expected)
    {
        var t = C(sql, d);
        Assert.Equal(expected, t.Control);
        Assert.Equal(expected != TransactionControl.None, t.Kind == StatementKind.Transaction);
    }

    [Theory]
    [InlineData("create table t (a int)", true)]
    [InlineData("alter table t add b int", true)]
