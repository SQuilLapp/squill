using Squill.Core;
using Squill.Core.Design;
using Squill.Sql.Ddl;
using Xunit;

namespace Squill.Sql.Tests;

public sealed class PostgresAlterTests
{
    private static ColumnDesign Col(string name, string type = "integer", bool nullable = true, string? def = null) =>
        new(name, name, type, nullable, def, false);

    private static TableDesign Base(string? schema = "public", string? keyName = null, string[]? key = null) =>
        new(schema, "t", [Col("id", nullable: false), Col("a"), Col("b", "text")], key ?? ["id"], keyName, [], []);

    private static IReadOnlyList<string> Alter(TableDesign o, TableDesign e) => DdlGenerators.For(DatabaseDialect.PostgreSql).Alter(o, e);

    private static TableDesign With(TableDesign t, ColumnDesign[]? columns = null, IndexDesign[]? indexes = null, ForeignKeyDesign[]? fks = null, string? name = null) =>
        t with { Columns = columns ?? t.Columns, Indexes = indexes ?? t.Indexes, ForeignKeys = fks ?? t.ForeignKeys, Name = name ?? t.Name };

    [Fact]
    public void Alter_RenameTable_Statement() =>
        Assert.Equal(["ALTER TABLE \"public\".\"t\" RENAME TO \"u\""], Alter(Base(), With(Base(), name: "u")));

    [Fact]
    public void Alter_AddAndDropColumn_Statements()
    {
        var o = Base();
        var added = With(o, [.. o.Columns, new ColumnDesign(null, "c", "integer", false, null, true)]);
        Assert.Equal(["ALTER TABLE \"public\".\"t\" ADD COLUMN \"c\" integer GENERATED BY DEFAULT AS IDENTITY NOT NULL"], Alter(o, added));
        Assert.Equal(["ALTER TABLE \"public\".\"t\" DROP COLUMN \"b\""], Alter(o, With(o, [o.Columns[0], o.Columns[1]])));
    }

    [Fact]
    public void Alter_RenameColumn_Statement()
    {
        var o = Base();
        var e = With(o, [o.Columns[0], o.Columns[1] with { Name = "z" }, o.Columns[2]]);
        Assert.Equal(["ALTER TABLE \"public\".\"t\" RENAME COLUMN \"a\" TO \"z\""], Alter(o, e));
    }

    [Fact]
    public void Alter_TypeNullabilityDefault_OneStatementEachInOrder()
    {
        var o = Base();
        var e = With(o, [o.Columns[0], o.Columns[1] with { DataType = "bigint", IsNullable = false, DefaultExpression = "0" }, o.Columns[2]]);
        Assert.Equal(
            [
                "ALTER TABLE \"public\".\"t\" ALTER COLUMN \"a\" TYPE bigint USING \"a\"::bigint",
                "ALTER TABLE \"public\".\"t\" ALTER COLUMN \"a\" SET NOT NULL",
                "ALTER TABLE \"public\".\"t\" ALTER COLUMN \"a\" SET DEFAULT 0",
            ],
            Alter(o, e));
    }

    [Fact]
    public void Alter_DropNotNullAndDefault_Statements()
    {
        var o = With(Base(), [Col("id", nullable: false), Col("a", nullable: false, def: "1")]);
        var e = With(o, [o.Columns[0], o.Columns[1] with { IsNullable = true, DefaultExpression = null }]);
        Assert.Equal(
            ["ALTER TABLE \"public\".\"t\" ALTER COLUMN \"a\" DROP NOT NULL", "ALTER TABLE \"public\".\"t\" ALTER COLUMN \"a\" DROP DEFAULT"],
            Alter(o, e));
    }

    [Theory]
    [InlineData(null, "t_pkey")]
    [InlineData("pk_custom", "pk_custom")]
    public void Alter_PrimaryKeyChange_DropsStoredOrDefaultName(string? stored, string dropped) =>
        Assert.Equal(
            [$"ALTER TABLE \"public\".\"t\" DROP CONSTRAINT \"{dropped}\"", "ALTER TABLE \"public\".\"t\" ADD PRIMARY KEY (\"id\", \"a\")"],
            Alter(Base(keyName: stored), Base(keyName: stored, key: ["id", "a"])));

    [Fact]
    public void Alter_Indexes_CreateAndDrop()
    {
        var o = With(Base(), indexes: [new IndexDesign("ix_a", "ix_a", false, ["a"])]);
        var e = With(o, indexes: [new IndexDesign(null, "ix_b", true, ["b"])]);
        Assert.Equal(
            ["DROP INDEX \"public\".\"ix_a\"", "CREATE UNIQUE INDEX \"public\".\"ix_b\" ON \"public\".\"t\" (\"b\")"],
            Alter(o, e));
        Assert.Equal(["DROP INDEX \"ix_a\""], Alter(o with { Schema = null }, e with { Schema = null, Indexes = [] }));
    }

    [Fact]
    public void Alter_ForeignKeys_AddAndDrop()
    {
        var fk = new ForeignKeyDesign("fk_a", "fk_a", ["a"], "ref", "r", ["id"], ReferentialAction.Cascade, ReferentialAction.NoAction);
        var o = With(Base(), fks: [fk]);
        Assert.Equal(["ALTER TABLE \"public\".\"t\" DROP CONSTRAINT \"fk_a\""], Alter(o, With(o, fks: [])));
        Assert.Equal(
            ["ALTER TABLE \"public\".\"t\" ADD CONSTRAINT \"fk_a\" FOREIGN KEY (\"a\") REFERENCES \"ref\".\"r\" (\"id\") ON DELETE CASCADE ON UPDATE NO ACTION"],
            Alter(Base(), With(Base(), fks: [fk with { OriginalName = null }])));
    }

    [Fact]
    public void Alter_MixedEdit_KeepsOperationOrder()
    {
        var o = With(Base(), indexes: [new IndexDesign("ix_a", "ix_a", false, ["a"])]);
        var e = With(o, [o.Columns[0], o.Columns[1] with { Name = "z" }, new ColumnDesign(null, "n", "text", true, null, false)], [], name: "u");
        Assert.Equal(
            [
                "DROP INDEX \"public\".\"ix_a\"",
                "ALTER TABLE \"public\".\"t\" DROP COLUMN \"b\"",
                "ALTER TABLE \"public\".\"t\" RENAME COLUMN \"a\" TO \"z\"",
                "ALTER TABLE \"public\".\"t\" ADD COLUMN \"n\" text",
                "ALTER TABLE \"public\".\"t\" RENAME TO \"u\"",
            ],
            Alter(o, e));
    }
}
