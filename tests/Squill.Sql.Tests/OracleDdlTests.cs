using Squill.Core;
using Squill.Core.Design;
using Squill.Sql.Ddl;
using Xunit;

namespace Squill.Sql.Tests;

public sealed class OracleDdlTests
{
    private static ColumnDesign Col(string name, string type = "NUMBER(10)", bool nullable = true, string? def = null, bool auto = false) =>
        new(name, name, type, nullable, def, auto);

    private static TableDesign Base(string? schema = "S") =>
        new(schema, "t", [Col("id", nullable: false), Col("a"), Col("b", "VARCHAR2(20)", false, "'x'")], ["id"], null, [], []);

    private static IReadOnlyList<string> Alter(TableDesign o, TableDesign e) => DdlGenerators.For(DatabaseDialect.Oracle).Alter(o, e);

    private static TableDesign With(TableDesign t, ColumnDesign[]? columns = null, IndexDesign[]? indexes = null, ForeignKeyDesign[]? fks = null, string? name = null, string[]? key = null) =>
        t with { Columns = columns ?? t.Columns, Indexes = indexes ?? t.Indexes, ForeignKeys = fks ?? t.ForeignKeys, Name = name ?? t.Name, PrimaryKey = key ?? t.PrimaryKey };

    [Fact]
    public void CreateTable_IdentityDefaultBeforeNotNull_InlineKeysAndIndex()
    {
        var table = new TableDesign("S", "orders",
            [Col("id", nullable: false, auto: true), Col("customer_id", nullable: false), Col("note", "VARCHAR2(40)", false, "'n'")],
            ["id"], "pk_orders",
            [new IndexDesign(null, "ix_note", true, ["note"])],
            [new ForeignKeyDesign(null, "fk_c", ["customer_id"], "S", "customers", ["id"], ReferentialAction.Cascade, ReferentialAction.NoAction)]);

        Assert.Equal(
            [
                "CREATE TABLE \"S\".\"orders\" (\n    \"id\" NUMBER(10) GENERATED BY DEFAULT AS IDENTITY NOT NULL,\n    \"customer_id\" NUMBER(10) NOT NULL,\n    \"note\" VARCHAR2(40) DEFAULT 'n' NOT NULL,\n"
                + "    CONSTRAINT \"pk_orders\" PRIMARY KEY (\"id\"),\n    CONSTRAINT \"fk_c\" FOREIGN KEY (\"customer_id\") REFERENCES \"S\".\"customers\" (\"id\") ON DELETE CASCADE\n)",
                "CREATE UNIQUE INDEX \"S\".\"ix_note\" ON \"S\".\"orders\" (\"note\")",
            ],
            DdlGenerators.For(DatabaseDialect.Oracle).CreateTable(table));
    }

    [Theory]
    [InlineData(ReferentialAction.NoAction, "")]
    [InlineData(ReferentialAction.SetNull, " ON DELETE SET NULL")]
    [InlineData(ReferentialAction.Cascade, " ON DELETE CASCADE")]
    public void CreateTable_ForeignKeyAction_OnlyOnDeleteCascadeAndSetNull(ReferentialAction action, string clause)
    {
        var table = Base(null) with { ForeignKeys = [new ForeignKeyDesign(null, "fk", ["a"], null, "p", ["id"], action, ReferentialAction.NoAction)] };
        Assert.EndsWith($"REFERENCES \"p\" (\"id\"){clause}\n)", DdlGenerators.For(DatabaseDialect.Oracle).CreateTable(table)[0], StringComparison.Ordinal);
    }

    [Fact]
    public void DropTable_HasNoCascadeConstraints() =>
        Assert.Equal(["DROP TABLE \"S\".\"t\""], DdlGenerators.For(DatabaseDialect.Oracle).DropTable("S", "t"));

    [Fact]
    public void Alter_RenameTable_NameIsNotQualified() =>
        Assert.Equal(["ALTER TABLE \"S\".\"t\" RENAME TO \"u\""], Alter(Base(), With(Base(), name: "u")));

    [Fact]
    public void Alter_AddAndDropColumn()
    {
        var o = Base();
        Assert.Equal(["ALTER TABLE \"S\".\"t\" ADD \"c\" NUMBER(10) DEFAULT 7 NOT NULL"],
            Alter(o, With(o, [.. o.Columns, new ColumnDesign(null, "c", "NUMBER(10)", false, "7", false)])));
        Assert.Equal(["ALTER TABLE \"S\".\"t\" DROP COLUMN \"b\""], Alter(o, With(o, [o.Columns[0], o.Columns[1]])));
    }

    [Fact]
    public void Alter_RenameColumn() =>
        Assert.Equal(["ALTER TABLE \"S\".\"t\" RENAME COLUMN \"a\" TO \"z\""], Alter(Base(), With(Base(), [Base().Columns[0], Base().Columns[1] with { Name = "z" }, Base().Columns[2]])));

    [Fact]
    public void Alter_Modify_RestatesOnlyTheChangedAspects()
    {
        var o = Base();
        string One(ColumnDesign b) => Assert.Single(Alter(o, With(o, [o.Columns[0], o.Columns[1], b])));
        Assert.Equal("ALTER TABLE \"S\".\"t\" MODIFY \"b\" VARCHAR2(30)", One(o.Columns[2] with { DataType = "VARCHAR2(30)" }));
        Assert.Equal("ALTER TABLE \"S\".\"t\" MODIFY \"b\" NULL", One(o.Columns[2] with { IsNullable = true }));
        Assert.Equal("ALTER TABLE \"S\".\"t\" MODIFY \"b\" DEFAULT 'y'", One(o.Columns[2] with { DefaultExpression = "'y'" }));
        Assert.Equal("ALTER TABLE \"S\".\"t\" MODIFY \"b\" DEFAULT NULL", One(o.Columns[2] with { DefaultExpression = null }));
        Assert.Equal("ALTER TABLE \"S\".\"t\" MODIFY \"b\" CLOB DEFAULT 'y' NULL", One(o.Columns[2] with { DataType = "CLOB", DefaultExpression = "'y'", IsNullable = true }));
    }

    [Fact]
    public void Alter_PrimaryKey_DropAndAdd()
    {
        var o = Base();
        Assert.Equal(["ALTER TABLE \"S\".\"t\" DROP PRIMARY KEY"], Alter(o, With(o, key: [])));
        var composite = With(o, [o.Columns[0], o.Columns[1] with { IsNullable = false }, o.Columns[2]], key: ["id", "a"]);
        Assert.Contains("ALTER TABLE \"S\".\"t\" ADD PRIMARY KEY (\"id\", \"a\")", Alter(o, composite));
    }

    [Fact]
    public void Alter_Indexes_AreSchemaQualified()
    {
        var o = Base();
        var ix = new IndexDesign(null, "ix_a", false, ["a"]);
        Assert.Equal(["CREATE INDEX \"S\".\"ix_a\" ON \"S\".\"t\" (\"a\")"], Alter(o, With(o, indexes: [ix])));
        Assert.Equal(["DROP INDEX \"S\".\"ix_a\""], Alter(With(o, indexes: [ix with { OriginalName = "ix_a" }]), o));
    }

    [Fact]
    public void Alter_ForeignKeys()
    {
        var o = Base();
        var fk = new ForeignKeyDesign(null, "fk_a", ["a"], "S", "p", ["id"], ReferentialAction.SetNull, ReferentialAction.NoAction);
        Assert.Equal(["ALTER TABLE \"S\".\"t\" ADD CONSTRAINT \"fk_a\" FOREIGN KEY (\"a\") REFERENCES \"S\".\"p\" (\"id\") ON DELETE SET NULL"], Alter(o, With(o, fks: [fk])));
        Assert.Equal(["ALTER TABLE \"S\".\"t\" DROP CONSTRAINT \"fk_a\""], Alter(With(o, fks: [fk with { OriginalName = "fk_a" }]), o));
    }

    [Theory]
    [InlineData(ReferentialAction.Restrict, ReferentialAction.NoAction)]
    [InlineData(ReferentialAction.SetDefault, ReferentialAction.NoAction)]
    [InlineData(ReferentialAction.NoAction, ReferentialAction.Cascade)]
    public void Validator_RefusesActionsOracleLacks(ReferentialAction onDelete, ReferentialAction onUpdate)
    {
        var t = Base() with { ForeignKeys = [new ForeignKeyDesign(null, "fk", ["a"], "S", "p", ["id"], onDelete, onUpdate)] };
        Assert.Contains(DesignValidator.Validate(t, null, DatabaseDialect.Oracle), i => i.Code == CoreMessageCodes.DesignOracleForeignKeyAction);
        Assert.DoesNotContain(DesignValidator.Validate(t, null, DatabaseDialect.PostgreSql), i => i.Code == CoreMessageCodes.DesignOracleForeignKeyAction);
    }
}
