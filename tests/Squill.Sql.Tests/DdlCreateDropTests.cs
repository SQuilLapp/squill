using Squill.Core;
using Squill.Core.Design;
using Squill.Sql.Ddl;
using Xunit;

namespace Squill.Sql.Tests;

public sealed class DdlCreateDropTests
{
    private static ColumnDesign Col(string name, string type, bool nullable = true, string? def = null, bool auto = false) =>
        new(null, name, type, nullable, def, auto);

    private static TableDesign Table(
        string? schema,
        IReadOnlyList<ColumnDesign> columns,
        string[]? key = null,
        string? keyName = null,
        IndexDesign[]? indexes = null,
        ForeignKeyDesign[]? fks = null) =>
        new(schema, "t", columns, key ?? [], keyName, indexes ?? [], fks ?? []);

    private static IReadOnlyList<string> Create(DatabaseDialect d, TableDesign t) => DdlGenerators.For(d).CreateTable(t);

    [Fact]
    public void CreateTable_SimplePostgres_ExactSql()
    {
        var t = Table("public", [Col("id", "integer", false), Col("name", "text", true, "'x'")], ["id"]);
        Assert.Equal(
            ["CREATE TABLE \"public\".\"t\" (\n    \"id\" integer NOT NULL,\n    \"name\" text DEFAULT 'x',\n    PRIMARY KEY (\"id\")\n)"],
            Create(DatabaseDialect.PostgreSql, t));
    }

    [Fact]
    public void CreateTable_SqlServer_WritesNullForNullableColumns()
    {
        var t = Table("dbo", [Col("id", "int", false), Col("name", "nvarchar(50)")], ["id"]);
        Assert.Equal(
            ["CREATE TABLE [dbo].[t] (\n    [id] int NOT NULL,\n    [name] nvarchar(50) NULL,\n    PRIMARY KEY ([id])\n)"],
            Create(DatabaseDialect.SqlServer, t));
    }

    [Fact]
    public void CreateTable_CompositeNamedKeyMySql_ExactSql()
    {
        var t = Table(null, [Col("a", "int", false), Col("b", "int", false)], ["a", "b"], "pk_t");
        Assert.Equal(
            ["CREATE TABLE `t` (\n    `a` int NOT NULL,\n    `b` int NOT NULL,\n    CONSTRAINT `pk_t` PRIMARY KEY (`a`, `b`)\n)"],
            Create(DatabaseDialect.MySql, t));
    }

    [Theory]
    [InlineData(DatabaseDialect.PostgreSql, "\"id\" integer GENERATED BY DEFAULT AS IDENTITY NOT NULL")]
    [InlineData(DatabaseDialect.MySql, "`id` integer AUTO_INCREMENT NOT NULL")]
    [InlineData(DatabaseDialect.SqlServer, "[id] integer IDENTITY(1,1) NOT NULL")]
    [InlineData(DatabaseDialect.Sqlite, "\"id\" INTEGER PRIMARY KEY AUTOINCREMENT")]
    public void CreateTable_AutoIncrementSoleKey_UsesEngineSyntax(DatabaseDialect d, string columnClause)
    {
        var statement = Create(d, Table(null, [Col("id", "integer", false, null, true)], ["id"]))[0];
        Assert.Contains("    " + columnClause, statement);
        Assert.Equal(d != DatabaseDialect.Sqlite, statement.Contains("PRIMARY KEY (", StringComparison.Ordinal));
    }

    [Fact]
    public void CreateTable_SqliteAutoIncrementInCompositeKey_IsIgnored()
    {
        var t = Table(null, [Col("a", "integer", false, null, true), Col("b", "integer", false)], ["a", "b"]);
        Assert.Equal(
            ["CREATE TABLE \"t\" (\n    \"a\" integer NOT NULL,\n    \"b\" integer NOT NULL,\n    PRIMARY KEY (\"a\", \"b\")\n)"],
            Create(DatabaseDialect.Sqlite, t));
    }

    [Fact]
    public void CreateTable_Indexes_FollowTheTable()
    {
        var t = Table(
            null,
            [Col("a", "int"), Col("b", "int")],
            indexes: [new IndexDesign(null, "ix_ab", false, ["a", "b"]), new IndexDesign(null, "ux_b", true, ["b"])]);
        var statements = Create(DatabaseDialect.MySql, t);
        Assert.Equal("CREATE INDEX `ix_ab` ON `t` (`a`, `b`)", statements[1]);
        Assert.Equal("CREATE UNIQUE INDEX `ux_b` ON `t` (`b`)", statements[2]);
    }

    [Theory]
    [InlineData(DatabaseDialect.PostgreSql, "CREATE INDEX \"s\".\"ix\" ON \"s\".\"t\" (\"a\")")]
    [InlineData(DatabaseDialect.SqlServer, "CREATE INDEX [ix] ON [s].[t] ([a])")]
    [InlineData(DatabaseDialect.MySql, "CREATE INDEX `ix` ON `s`.`t` (`a`)")]
    [InlineData(DatabaseDialect.Sqlite, "CREATE INDEX \"s\".\"ix\" ON \"s\".\"t\" (\"a\")")]
    public void CreateTable_IndexOnSchemaTable_QualifiesNameByDialect(DatabaseDialect d, string expected) =>
        Assert.Equal(expected, Create(d, Table("s", [Col("a", "int")], indexes: [new IndexDesign(null, "ix", false, ["a"])]))[1]);

    [Fact]
    public void CreateTable_SqliteMainSchema_LeavesIndexNameUnqualified() =>
        Assert.Equal(
            "CREATE INDEX \"ix\" ON \"main\".\"t\" (\"a\")",
            Create(DatabaseDialect.Sqlite, Table("main", [Col("a", "int")], indexes: [new IndexDesign(null, "ix", false, ["a"])]))[1]);

    [Fact]
    public void CreateTable_ForeignKeyWithActionsAndSchema_ExactSql()
    {
        var fk = new ForeignKeyDesign(null, "fk_o", ["cid"], "crm", "customer", ["id"], ReferentialAction.Cascade, ReferentialAction.SetNull);
        var t = Table("sales", [Col("cid", "int", false)], fks: [fk]);
        Assert.Equal(
            ["CREATE TABLE [sales].[t] (\n    [cid] int NOT NULL,\n    CONSTRAINT [fk_o] FOREIGN KEY ([cid]) REFERENCES [crm].[customer] ([id]) ON DELETE CASCADE ON UPDATE SET NULL\n)"],
            Create(DatabaseDialect.SqlServer, t));
    }

    [Fact]
    public void CreateTable_EmbeddedQuotes_AreDoubled()
    {
        var t = Table(null, [Col("a\"b", "int")]);
        Assert.Equal(["CREATE TABLE \"t\" (\n    \"a\"\"b\" int\n)"], Create(DatabaseDialect.PostgreSql, t));
    }

    [Fact]
    public void CreateTable_NoColumns_Throws() =>
        Assert.Throws<ArgumentException>(() => Create(DatabaseDialect.Sqlite, TableDesign.New(null, "t")));

    [Theory]
    [InlineData(DatabaseDialect.PostgreSql, "DROP TABLE \"s\".\"t\"")]
    [InlineData(DatabaseDialect.MySql, "DROP TABLE `s`.`t`")]
    [InlineData(DatabaseDialect.SqlServer, "DROP TABLE [s].[t]")]
    [InlineData(DatabaseDialect.Sqlite, "DROP TABLE \"s\".\"t\"")]
    public void DropTable_Qualified_ExactSql(DatabaseDialect d, string expected) =>
        Assert.Equal([expected], DdlGenerators.For(d).DropTable("s", "t"));

    [Fact]
    public void ToScript_JoinsWithBlankLineAndTerminates()
    {
        Assert.Equal("A;\n\nB;", DdlGenerators.ToScript(["A", "B"]));
        Assert.Equal("", DdlGenerators.ToScript([]));
    }

    [Theory]
    [InlineData(DatabaseDialect.PostgreSql, true)]
    [InlineData(DatabaseDialect.SqlServer, true)]
    [InlineData(DatabaseDialect.Sqlite, true)]
    [InlineData(DatabaseDialect.MySql, false)]
    public void UsesTransactionalDdl_ByDialect(DatabaseDialect d, bool expected) =>
        Assert.Equal(expected, DdlGenerators.UsesTransactionalDdl(d));
}
